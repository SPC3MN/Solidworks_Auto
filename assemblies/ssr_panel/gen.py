"""Generate the SSR panel: the part projects (panel, DIN rail, terminal, two PSUs) and
assemblies/ssr_panel/assembly.json. Electronics only, no wiring.

Layout from the user's two photos. Scale: the SSR-RACK48 is 431.8 mm long (measured by the user)
and spans 1230 px, so about 0.351 mm/px in the panel plane. Every position and size below is
ESTIMATED except the rack itself. Assembly axes: the panel in the XY plane, x to the right,
y up (as hung), z out of the panel toward the viewer, origin at the panel's bottom-left corner.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import panel_parts as pp  # noqa: E402

PANEL = {"l": 340.0, "w": 600.0, "t": 6.35}
T = PANEL["t"]
STANDOFF = 11.0                       # standoff_m25 length
# SSR-RACK48, rotated +90 deg: rack x (length) runs up the panel, its terminal edge (rack y = 0) faces right
RACK_AT = (PANEL["l"] / 2 + 114.3 / 2, 76.1)  # rack origin: centred across the panel width (x 170, user), y centre 292
RACK_HOLES = [(x, y) for x in (4.8, 143.933, 287.867, 427.0) for y in (4.8, 109.5)]
RAIL = {"length": 469.0, "slot_pitch": 25.0, "slot_l": 15.0, "slot_w": 5.2, "t": 1.0, "h": 7.5}
RAIL_X, RAIL_Y0 = 36.0, 79.0          # rail centre line and bottom end
TERM = {"pitch": 8.2, "w_base": 50.0, "w_mid": 36.0, "w_top": 16.0, "z_base": 20.0, "z_mid": 32.0, "h": 42.0,
        "screw_d": 3.6, "screw_depth": 6.0, "wire": 4.0, "wire_z": 10.0, "wire_depth": 8.0}
GROUPS = [(530.0, 16), (375.0, 16), (220.0, 16)]  # (top y, terminal count): 3 groups of 16 (user)
PSU_X = 311.0
PSUS = [  # (project, length, outward height, bottom y)
    ("psu_lrs350", 215.0, 115.0, 375.0),
    ("psu_lrs150", 159.0, 97.0, 211.0),
    ("psu_lrs150", 159.0, 97.0, 31.0),
]
PSU_COMMON = {"t": 30.0, "wall": 1.0, "cols": 4, "hole_d": 4.0, "hole_pitch": 6.0, "hole_margin": 15.0,
              # terminal end and side details (estimated, typical LRS layout)
              "tb_len": 14.0, "terminals": 7, "tb_margin": 8.0, "tb_top": 22.0,
              "screw_d": 5.0, "screw_depth": 2.0, "groove_w": 1.0, "groove_depth": 3.0,
              "pot_d": 4.0, "pot_h": 1.5, "led_d": 3.0, "led_h": 1.0,
              "vent_l": 20.0, "vent_w": 3.0, "vent_pitch": 8.0, "vent_margin": 10.0, "vent_from_edge": 18.0}


def rack_to_panel(x, y):
    """Rack local (x, y) -> panel (X, Y) for rot_z = +90: (x, y) -> (-y, x), then translate."""
    return RACK_AT[0] - y, RACK_AT[1] + x


def project(name, kind, params, requirements):
    d = ROOT / "projects" / name
    for s in ("design", "parameters", "validation"):
        (d / s).mkdir(parents=True, exist_ok=True)
    (d / "parameters" / "params.json").write_text(json.dumps(params, indent=1))
    (d / "design" / "model.py").write_text(
        f'"""{name}: built by scripts/panel_parts.py ({kind}_build). Generated by assemblies/ssr_panel/gen.py."""\n'
        "import pathlib\nimport sys\n\n"
        'sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "scripts"))\n'
        "import panel_parts  # noqa: E402\n\n\n"
        f"def build(app, params):\n    return panel_parts.{kind}_build(app, params)\n")
    vol, bb = getattr(pp, f"{kind}_expected")(params)
    spec = {"_comment": "Expected values come from requirements.md (panel_parts arithmetic).",
            "solid_bodies": {"expected": 1},
            "bbox.x": {"expected": bb[0], "tol": 0.05}, "bbox.y": {"expected": bb[1], "tol": 0.05},
            "bbox.z": {"expected": bb[2], "tol": 0.05}, "volume": {"expected": vol, "rel_tol": 0.001},
            "export.step": {"rel_tol": 0.001}, "export.stl": {"rel_tol": 0.01}}
    (d / "validation" / "spec.json").write_text(json.dumps(spec, indent=1))
    (d / "requirements.md").write_text(requirements.format(vol=vol, bb=" x ".join(f"{v:g}" for v in bb)), encoding="utf-8")
    return vol, bb


def main():
    standoffs = [rack_to_panel(x, y) for x, y in RACK_HOLES]
    panel = dict(PANEL, holes=[{"x": round(x, 3), "y": round(y, 3), "d": 3.0} for x, y in standoffs])
    project("acrylic_panel", "panel", panel, """# Acrylic mounting panel (SSR panel)

Black acrylic sheet that carries the SSR-RACK48, the DIN rail with its terminals, and three power
supplies. Size and thickness are **estimated** from the user's photos (scale taken from the
431.8 mm rack): about 340 x 600 mm, 1/4 in (6.35 mm) thick. Eight Ø3 holes take the screws for
the rack's M2.5 standoffs (positions follow the rack's hole pattern). The rail and supply fixings are not drilled.

## Expected values
- 340 x 600 x 6.35 = 1295400, less 8 x π·1.5²·6.35 = 359.1, gives **{vol} mm³**
- Bounding box {bb}
""")
    project("din_rail_ts35", "rail", RAIL, """# TS35 DIN rail (top hat, 35 x 7.5)

Standard profile (EN 60715): 35 mm wide and 7.5 mm high, 1 mm steel, with a 27 mm base. There are
15 x 5.2 slots at 25 mm pitch along the base. The 469 mm length is **estimated** from the photo.

## Expected values
- Profile area = 27·1 + 2·(1·5.5) + 2·(5·1) = 48 mm²; times 469 = 22512
- Slots: n x ((15-5.2)·5.2 + π·2.6²)·1 removed
- **{vol} mm³**, bounding box {bb}
""")
    project("din_terminal", "terminal", TERM, """# DIN-rail screw terminal (one position)

Blue feed-through terminal like the ones in the photo, in 3 groups of 16 (given by the user). Pitch 8.2 mm (16 per group spans about 140 mm in the photo, so a 6 mm² size); 50 mm across the rail;
42 mm tall above the rail. The stepped body has two screw pockets (Ø3.6, 6 deep) and two wire
entries (4 x 4, 8 deep). Sizes are **estimated** (typical 4 mm² terminal). The latch that
grips the rail is not modelled: the body sits on the rail flanges.

## Expected values
- Profile 50·20 + 36·12 + 16·10 = 1592 mm²; times 8.2 = 13054.4
- Less screws 2·π·1.8²·6 = 122.15 and wire entries 2·4·4·8 = 256
- **{vol} mm³**, bounding box {bb}
""")
    for name, L, H, _ in PSUS[:2]:
        model = "LRS-350" if L > 200 else "LRS-150"
        project(name, "psu", dict(PSU_COMMON, l=L, h=H), f"""# Enclosed power supply, Mean Well {model} size

Mounted on edge on the panel, perforated face outward. The case is {L:g} x {H:g} x 30 mm: the
size of a Mean Well {model}, **estimated** from the photo. The parts:
- a closed sheet-metal case with 1 mm walls and no internals;
- Ø4 perforations at 6 mm pitch, in 4 columns, on the outward face;
- 3 × 20 vent slots at 8 mm pitch, two rows on each big side face;
- at the bottom end, a solid 14 mm terminal block with 7 screw pockets (Ø5, 2 deep) and barrier
  grooves between them on its side face;
- a V-adjust pot (Ø4, 1.5 proud) and a power LED (Ø3, 1 proud) above the screws.

All detail sizes are **estimated**.
"""
                + """
## Expected values
- Case (L-14 long): outer less inner box, less the perforations n·π·2²·1 and the vents (2 sides × n × slot area × 1)
- Plus the terminal block 14·30·H, less 7 screw pockets π·2.5²·2 and 6 grooves 12·1·3
- Plus the pot π·2²·1.5 and the LED π·1.5²·1
- **{vol} mm³**, bounding box {bb}
""")
    comps = [{"part": "acrylic_panel"}]
    comps += [{"part": "standoff_m25", "label": f"standoff_{i + 1}", "at": [round(x, 3), round(y, 3), T]}
              for i, (x, y) in enumerate(standoffs)]
    comps.append({"part": "ssr_rack48", "at": [RACK_AT[0], RACK_AT[1], T + STANDOFF], "rot_z": 90})
    comps.append({"part": "din_rail_ts35", "at": [RAIL_X, RAIL_Y0, T]})
    for g, (top, n) in enumerate(GROUPS, 1):
        for k in range(n):
            y = top - (k + 1) * TERM["pitch"]
            comps.append({"part": "din_terminal", "label": f"tb{g}_{k + 1}", "at": [RAIL_X, round(y, 3), T + RAIL["h"]]})
    for name, L, H, y0 in PSUS:
        comps.append({"part": name, "label": f"{name}_{int(y0)}", "at": [PSU_X, y0, T]})
    top = max(T + STANDOFF + 38.1, T + RAIL["h"] + TERM["h"], max(T + H for _, _, H, _ in PSUS))
    asm = {"_comment": __doc__.strip().replace("\n", " "),
           "components": comps,
           "expected": {"_comment": "panel 340 x 600; z from the panel back to the tallest part (LRS-350, 6.35 + 115)",
                        "bbox": [PANEL["l"], PANEL["w"], round(top, 3)], "views": ["isometric", "top", "front"],
                        "allowed_interference": []}}
    out = pathlib.Path(__file__).parent / "assembly.json"
    out.write_text(json.dumps(asm, indent=1))
    print(len(comps), "components; bbox", asm["expected"]["bbox"])


if __name__ == "__main__":
    main()
